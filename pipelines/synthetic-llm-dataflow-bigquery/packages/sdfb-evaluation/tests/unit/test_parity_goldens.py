"""The MIRROR's side of the two-sided golden parity test (D2).

`tests/fixtures/parity/goldens.json` is generated by
`scripts/evaluation/make_parity_goldens.py`, run in the ROOT environment
against the ORIGINALS (`sdfb_core.contracts.relationships`,
`sdfb_core.rag.chunking`, `sdfb_beam.io.digest`,
`sdfb_beam.io.bq_sources`, `sdfb_beam.io.relationships`). This test recomputes the same values from
THIS package's mirrors (`sdfb_evaluation.context.relationships`,
`sdfb_evaluation.context.reference`) and asserts equality. The originals'
side of the pair — recomputing the same golden from the originals AGAIN,
as a regression pin — lives at
`packages/sdfb-tests/tests/unit/evaluation_parity/test_goldens.py`.
Neither test imports the other package, so neither can drift without the
golden file itself catching it (regenerate with
`UV_PROJECT_ENVIRONMENT=.venv-master uv run python
scripts/evaluation/make_parity_goldens.py`).

Design: docs/designs/2026-07-07-evaluation-framework-design.md
"""

from __future__ import annotations

import base64
from datetime import date, datetime
from decimal import Decimal
from typing import Any

from sdfb_evaluation.context.reference import (
    EXPOSURE_ROWS,
    reference_digest,
    reference_sql,
)
from sdfb_evaluation.context.relationships import (
    component,
    derived_widenings,
    enforced_edges,
    from_sources,
    generation_order,
    is_sample_model,
    sha12,
)


def _decode_value(  # noqa: PLR0911 — type dispatch, clearer flat than nested
    value: Any,) -> Any:
  """The inverse of the goldens script's `_encode_value`: a type-tagged
  JSON value back to the native Python object `reference_digest` expects.
  """
  if isinstance(value, dict):
    if "$decimal" in value:
      return Decimal(value["$decimal"])
    if "$datetime" in value:
      return datetime.fromisoformat(value["$datetime"])
    if "$date" in value:
      return date.fromisoformat(value["$date"])
    if "$bytes" in value:
      return base64.b64decode(value["$bytes"])
    return {k: _decode_value(v) for k, v in value.items()}
  if isinstance(value, list):
    return [_decode_value(v) for v in value]
  return value


def _decode_row(row: dict[str, Any]) -> dict[str, Any]:
  return {k: _decode_value(v) for k, v in row.items()}


# ---------------------------------------------------------------------------
# Relationship models: sha12, component, generation_order, enforced_edges,
# derived_widenings — including an invented widening model and a
# multi-source (two files, one registry) entry.
# ---------------------------------------------------------------------------


def test_model_goldens_match_the_mirror(load_fixture):
  goldens = load_fixture("parity/goldens.json")
  for name, expected in goldens["models"].items():
    sources = [tuple(pair) for pair in expected["sources"]]
    models = from_sources(sources)
    assert sha12(models) == expected["sha12"], name
    for table, expected_component in expected["component"].items():
      assert list(component(models, table)) == expected_component, (name, table)
    for table, expected_order in expected["generation_order"].items():
      actual_order = list(generation_order(models, component(models, table)))
      assert actual_order == expected_order, (name, table)
    for table, expected_edges in expected["enforced_edges"].items():
      actual_edges = [[
          list(e.cols), e.ref,
          list(e.ref_cols), e.enforced, e.drives
      ] for e in enforced_edges(models, table)]
      assert actual_edges == expected_edges, (name, table)
    expected_widenings = [[rec[0], rec[1], rec[2], [tuple(p)
                                                    for p in rec[3]]]
                          for rec in expected["derived_widenings"]]
    actual_widenings = [[rec["table"], rec["ref"], rec["via"], rec["added"]]
                        for rec in derived_widenings(models)]
    assert actual_widenings == expected_widenings, name


# ---------------------------------------------------------------------------
# parse_model / from_sources strictness — accept/reject verdicts
# ---------------------------------------------------------------------------


def test_parse_verdicts_match_the_mirror(load_fixture):
  goldens = load_fixture("parity/goldens.json")["parse_verdicts"]
  for entry in goldens:
    sources = [tuple(pair) for pair in entry["sources"]]
    if entry["accept"]:
      models = from_sources(sources)
      assert sha12(models) == entry["sha12"], entry["case"]
    else:
      try:
        from_sources(sources)
      except Exception as exc:  # pylint: disable=broad-except
        assert type(exc).__name__ == entry["error_class"], entry["case"]
      else:
        case = entry["case"]
        raise AssertionError(f"{case}: expected a rejection")


